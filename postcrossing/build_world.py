"""Builds postcrossing/world.js, the base map for the Postcrossing section.

Country shapes come from world-atlas@2.0.2 (Natural Earth 1:110m, public domain),
re-keyed from ISO numeric ids to the 2-letter codes Postcrossing uses in postcard
IDs (e.g. "FR-1947926" -> "FR"). Places too small to appear at 1:110m (Macao,
Hong Kong, Singapore, ...) get a lon/lat point taken from the 1:50m map instead.

Only needs re-running to change the base map; postcard counts live in received.js.
    python postcrossing/build_world.py
"""
import json
import pathlib
import urllib.request

CDN = "https://cdn.jsdelivr.net/npm/"
OUT = pathlib.Path(__file__).with_name("world.js")

# Places without an ISO numeric id in Natural Earth.
NAME_TO_CODE = {"Kosovo": "XK"}
# Postcrossing regions that Natural Earth folds into another country.
# (French Guiana is big enough to be split out of France as its own shape below.)
EXTRA_POINTS = {
    "GP": [-61.55, 16.25],   # Guadeloupe
    "MQ": [-61.02, 14.64],   # Martinique
    "RE": [55.53, -21.13],   # Réunion
    "YT": [45.17, -12.83],   # Mayotte
}


def fetch_json(path):
    with urllib.request.urlopen(CDN + path) as r:
        return json.load(r)


def code_of(geom, numeric_to_code):
    return numeric_to_code.get(geom.get("id")) or NAME_TO_CODE.get(geom["properties"]["name"])


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    return arcs


def ring_coords(ring, arcs):
    pts = []
    for i in ring:
        seg = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(seg if not pts else seg[1:])
    return pts


def representative_point(geom, arcs):
    """Centroid of the geometry's largest polygon (planar, fine for small places)."""
    polys = [geom["arcs"]] if geom["type"] == "Polygon" else geom["arcs"]
    best = None
    for poly in polys:
        pts = ring_coords(poly[0], arcs)
        a = cx = cy = 0.0
        for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
            cross = x0 * y1 - x1 * y0
            a += cross
            cx += (x0 + x1) * cross
            cy += (y0 + y1) * cross
        if a and (best is None or abs(a) > best[0]):
            best = (abs(a), [round(cx / (3 * a), 2), round(cy / (3 * a), 2)])
    return best[1]


def remap_arcs(arcs_field, remap):
    if isinstance(arcs_field, int):
        return remap[arcs_field] if arcs_field >= 0 else ~remap[~arcs_field]
    return [remap_arcs(a, remap) for a in arcs_field]


def collect_arcs(arcs_field, used):
    if isinstance(arcs_field, int):
        used.add(arcs_field if arcs_field >= 0 else ~arcs_field)
    else:
        for a in arcs_field:
            collect_arcs(a, used)


def main():
    numeric_to_code = {num: a2 for a2, _a3, num, *_ in fetch_json("i18n-iso-countries@7.11.0/codes.json")}
    topo = fetch_json("world-atlas@2.0.2/countries-110m.json")
    detail = fetch_json("world-atlas@2.0.2/countries-50m.json")

    topo_arcs = decode_arcs(topo)
    geoms = []
    for g in topo["objects"]["countries"]["geometries"]:
        code = code_of(g, numeric_to_code)
        if code == "AQ":
            continue  # Antarctica: no postcards, lots of pixels
        g = {k: v for k, v in g.items() if k not in ("id", "properties")}
        if code:
            g["id"] = code
        if code == "FR" and g["type"] == "MultiPolygon":
            # Postcrossing counts French Guiana (GF) separately from France.
            guiana = [p for p in g["arcs"] if representative_point({"type": "Polygon", "arcs": p}, topo_arcs)[0] < -20]
            g["arcs"] = [p for p in g["arcs"] if p not in guiana]
            geoms.append({"type": "MultiPolygon", "arcs": guiana, "id": "GF"})
        geoms.append(g)

    # Drop arcs only Antarctica used, then renumber.
    used = set()
    for g in geoms:
        collect_arcs(g["arcs"], used)
    remap = {old: new for new, old in enumerate(sorted(used))}
    for g in geoms:
        g["arcs"] = remap_arcs(g["arcs"], remap)
    topo["arcs"] = [topo["arcs"][i] for i in sorted(used)]
    topo["objects"] = {"countries": {"type": "GeometryCollection", "geometries": geoms}}

    have = {g.get("id") for g in geoms}
    detail_arcs = decode_arcs(detail)
    points = {}
    for g in detail["objects"]["countries"]["geometries"]:
        code = code_of(g, numeric_to_code)
        if code and code not in have and code not in points and g.get("arcs"):
            points[code] = representative_point(g, detail_arcs)
    points.update(EXTRA_POINTS)

    data = {"topology": topo, "points": dict(sorted(points.items()))}
    OUT.write_text(
        "// Generated by build_world.py from world-atlas@2.0.2 (Natural Earth, public domain). Do not edit.\n"
        "window.POSTCROSSING_WORLD = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB): {len(geoms)} shapes, {len(points)} points")


if __name__ == "__main__":
    main()
